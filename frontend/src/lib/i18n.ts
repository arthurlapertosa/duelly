export function normalizeLocale(value: string | null | undefined): Locale {
  return value === 'en-US' ? 'en-US' : defaultLocale;
}

export function translate(locale: Locale, key: string, params: Record<string, string | number> = {}): string {
  const template = dictionaries[locale][key] ?? dictionaries[defaultLocale][key] ?? key;
  return Object.entries(params).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), template);
}

export function missingTranslationKeys(): string[] {
  const keys = new Set(Object.keys(dictionaries[defaultLocale]));
  return locales.flatMap((locale) => [...keys].filter((key) => !dictionaries[locale][key]).map((key) => `${locale}:${key}`));
}

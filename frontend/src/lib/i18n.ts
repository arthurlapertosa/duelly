export function normalizeLocale(value: string | null | undefined): Locale {
  return value === 'pt-BR' ? 'pt-BR' : defaultLocale;
}

export function translate(locale: Locale, key: string, params: Record<string, string | number> = {}): string {
  const template = dictionaries[locale][key] ?? dictionaries[defaultLocale][key] ?? key;
  return Object.entries(params).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), template);
}

export function missingTranslationKeys(): string[] {
  const keys = new Set(Object.keys(dictionaries[defaultLocale]));
  return locales.flatMap((locale) => [...keys].filter((key) => !dictionaries[locale][key]).map((key) => `${locale}:${key}`));
}

/**
 * Localizes an outcome label coming from backend template data.
 *
 * Template content (titles, rules, and most outcome labels) is authored
 * English on the backend; full localization of that content is a backend
 * follow-up (the API would need to return locale-aware copy). As a stopgap
 * we only translate the *generic* binary labels — the literal strings
 * "Yes" / "No" — to "Sim" / "Não" in pt-BR so the most common duels read
 * naturally. Any other label is passed through untouched.
 */
export function localizeOutcomeLabel(locale: Locale, label: string): string {
  const normalized = label.trim().toLowerCase();
  if (normalized === 'yes') return translate(locale, 'common.yes');
  if (normalized === 'no') return translate(locale, 'common.no');
  return label;
}
